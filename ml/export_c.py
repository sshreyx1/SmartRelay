#!/usr/bin/env python3
"""
export_c.py - write the trained two-stage model (ml/models/model_<phase>.pkl) as C:
firmware/sensing/sound_model.h, read by sound_classify.c. Self-written, in the style of Maryam's
weather_tree.h (no emlearn / micromlgen): flat static const arrays per tree, in flash.

Per tree: feature index (int8), threshold (float, rounded DOWN to float32 so `x <= thr` in C is the
same test sklearn makes in double), left/right child (int16; negative = leaf), leaf class
distributions (uint8 percent). The header comment records the training date, data, chosen models,
test metrics and SF_VERSION, and the file refuses to compile against a different feature count.

--vectors also writes host/tests/sound_model_vectors.h: 200 test captures (features + the label and
confidence ml/qmodel.py computes for them); host/tests/test_sound_model.c demands a 100% match.

Run:      python ml/export_c.py --vectors
"""
import argparse
import pickle
import sys

import numpy as np

from mlcommon import ML_DIR, REPO_ROOT, resolve, sc

sys.path.insert(0, str(REPO_ROOT / "tools"))
from c_style import finish_c_file  # noqa: E402

OUT = REPO_ROOT / "firmware" / "sensing" / "sound_model.h"
VEC_OUT = REPO_ROOT / "host" / "tests" / "sound_model_vectors.h"
N_VECTORS = 200


def f32_down(x: float) -> np.float32:
    f = np.float32(x)
    if float(f) > x:
        f = np.nextafter(f, np.float32(-np.inf))
    return f


def cfloat(v) -> str:
    s = "%.9g" % float(v)
    if not any(ch in s for ch in ".eni"):
        s += ".0"
    return s + "f"


def arr(ctype: str, name: str, vals: list, fmt=str, per_line: int = 16) -> str:
    vals = list(vals) or [0]  # C has no empty arrays; an unused 0 keeps it legal
    body = ",\n    ".join(", ".join(fmt(v) for v in vals[i:i + per_line]) for i in range(0, len(vals), per_line))
    return f"static const {ctype} {name}[] = {{\n    {body}}};\n"


def emit_model(prefix: str, q) -> str:
    out = []
    tree_inits = []
    for ti, t in enumerate(q.trees):
        internal = [int(n) for n in np.where(t.left != -1)[0]]
        leaves = [int(n) for n in np.where(t.left == -1)[0]]
        code = {n: i for i, n in enumerate(internal)}
        code.update({n: -(i + 1) for i, n in enumerate(leaves)})
        p = f"{prefix}_t{ti}"
        out.append(arr("int8_t", f"{p}_feat", [int(t.feature[n]) for n in internal]))
        out.append(arr("float32_t", f"{p}_thr", [f32_down(float(t.threshold[n])) for n in internal], cfloat, 6))
        out.append(arr("int16_t", f"{p}_left", [code[int(t.left[n])] for n in internal]))
        out.append(arr("int16_t", f"{p}_right", [code[int(t.right[n])] for n in internal]))
        out.append(arr("uint8_t", f"{p}_leaf", [int(v) for n in leaves for v in t.leaf_pct[n]], per_line=len(q.classes)))
        tree_inits.append(f"    {{{p}_feat, {p}_thr, {p}_left, {p}_right, {p}_leaf, {code[0]}}},")
    out.append(f"static const sm_tree_t {prefix}_trees[] = {{\n" + "\n".join(tree_inits) + "\n};\n")
    names = ", ".join(f"SC_{sc.name(c)}" for c in q.classes)
    out.append(f"static const uint8_t {prefix}_classes[] = {{{names}}};\n")
    out.append(f"static const sm_model_t {prefix} = {{{prefix}_trees, {len(q.trees)}, {len(q.classes)}, "
               f"{prefix}_classes}};\n")
    out.append(f"static inline void {prefix}_predict(const float32_t* p_features, uint8_t* p_label, uint8_t* p_conf)\n"
               f"{{\n    sm_predict(&{prefix}, p_features, p_label, p_conf);\n}}\n")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description="Export the trained sound model to firmware/sensing/sound_model.h.")
    ap.add_argument("--phase", default="A")
    ap.add_argument("--vectors", action="store_true", help="also write host/tests/sound_model_vectors.h")
    args = ap.parse_args()

    pkl = ML_DIR / "models" / f"model_{args.phase}.pkl"
    if not pkl.exists():
        print(f"error: {pkl} not found, run train.py first", file=sys.stderr)
        return 1
    with open(pkl, "rb") as f:
        d = pickle.load(f)
    model, m = d["model"], d["metrics"]
    t = m["test"]
    if len(d["features"]) != 25:
        print("error: this exporter expects the 25 v1 features", file=sys.stderr)
        return 1
    for q in [model.stage1] + list(model.stage2.values()):
        if len(q.classes) > 16:
            print("error: more than SM_MAX_CLASSES classes", file=sys.stderr)
            return 1

    chosen = "\n".join(f" *   {k:>3}: {v['model']} (val macro-F1 {v['val_macro_f1']:.3f}, {v['nodes']} nodes)"
                       for k, v in m["chosen"].items())
    note = f" * {m['data_note']}\n *\n" if m["data_note"] else ""
    head = f"""/*
 * sound_model.h - GENERATED by ml/export_c.py from ml/models/model_{args.phase}.pkl. Do not edit by hand:
 * retrain (ml/train.py) and export again. Included only by sound_classify.c.
 *
{note} * trained {m['date']} on {m['features_csv']} ({m['n_takes']} takes, grid {m['grid']}, random_state 0)
 * features: sound_features.c v1, {len(d['features'])} values
 * chosen models (stage1 = group, 1/2/3 = stage 2 for BIRD/MAMMAL/INSECT_FROG):
{chosen}
 * SOUND_STAGE2_MIN_CONF {m['stage2_min_conf']} (combined confidence, chosen on the validation fold)
 * test fold: group acc {t['group_accuracy']:.3f}, macro-F1 {t['group_macro_f1']:.3f} | label acc
 *            {t['label_accuracy']:.3f}, macro-F1 {t['label_macro_f1']:.3f} | coverage {t['coverage']:.3f}
 * flash: about {m['model_flash_bytes']} bytes
 */
#ifndef SOUND_MODEL_H
#define SOUND_MODEL_H

#include <stdint.h>

#include "float_types.h"
#include "sound_classes.h"
#include "sound_classify.h"
#include "sound_features.h"

#if (1 != SF_VERSION) || ({len(d['features'])} != SF_N_FEATURES)
#error "sound_model.h was trained on sound_features v1 (25 features): " \\
    "retrain and export again"
#endif

#define SOUND_MODEL_DATE "{m['date']}"
#define SOUND_STAGE2_MIN_CONF {m['stage2_min_conf']}

"""
    body = [emit_model("sm_stage1", model.stage1)]
    cases = []
    for g, q in sorted(model.stage2.items()):
        name = f"sm_stage2_{sc.name(g).lower()}"
        body.append(emit_model(name, q))
        cases.append(f"    case SC_{sc.name(g)}:\n        return &{name};")
    tail = ("/* stage-2 model for a group id, or NULL if that group has none */\n"
            "static inline const sm_model_t* sm_stage2_for_group(uint8_t group)\n{\n    switch (group)\n    {\n"
            + "\n".join(cases) + "\n    default:\n        return 0;\n    }\n}\n\n#endif\n")
    OUT.write_text(head + "\n".join(body) + "\n" + tail, encoding="utf-8", newline="\n")
    finish_c_file(OUT)
    print(f"wrote {OUT.relative_to(REPO_ROOT)}")

    if args.vectors:
        import pandas as pd
        csvs = d["features_csv"] if isinstance(d["features_csv"], list) else [d["features_csv"]]
        df = pd.concat([pd.read_csv(resolve(c)) for c in csvs], ignore_index=True)
        rows = d["test_rows"]
        pick = [rows[int(i)] for i in np.linspace(0, len(rows) - 1, min(N_VECTORS, len(rows)))]
        X = df.loc[pick, d["features"]].to_numpy(np.float32)
        label, conf, *_ = model.predict(X)
        feats = ",\n    ".join("{" + ", ".join(cfloat(v) for v in row) + "}" for row in X)
        VEC_OUT.write_text(f"""/*
 * sound_model_vectors.h - GENERATED by ml/export_c.py --vectors. {len(pick)} test-fold captures with the label
 * and confidence ml/qmodel.py (the Python twin of sound_classify.c) gives them. Model of {m['date']}.
 */
#ifndef SOUND_MODEL_VECTORS_H
#define SOUND_MODEL_VECTORS_H

#include "float_types.h"
#include <stdint.h>

#define SM_N_VECTORS {len(pick)}

static const float32_t sm_vec_features[SM_N_VECTORS][{len(d['features'])}] = {{
    {feats}}};

static const uint8_t sm_vec_label[SM_N_VECTORS] = {{{", ".join(str(int(v)) for v in label)}}};
static const uint8_t sm_vec_conf[SM_N_VECTORS] = {{{", ".join(str(int(v)) for v in conf)}}};

#endif
""", encoding="utf-8", newline="\n")
        finish_c_file(VEC_OUT)
        print(f"wrote {VEC_OUT.relative_to(REPO_ROOT)} ({len(pick)} vectors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
