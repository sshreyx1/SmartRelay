#!/usr/bin/env python3
"""Regenerates alfp/src/alfp_crc_tables.c.

CRC-16/CCITT-FALSE: poly 0x1021, init 0xFFFF, no reflection, xorout 0. Check value for "123456789" = 0x29B1.
CRC-32 (IEEE 802.3 / zlib): reflected poly 0xEDB88320, init and xorout 0xFFFFFFFF. Check value = 0xCBF43926.

Usage: python3 tools/gen_crc_tables.py
"""
import os
from pathlib import Path

from c_style import finish_c_file


def crc16_table():
    t = []
    for i in range(256):
        c = i << 8
        for _ in range(8):
            c = ((c << 1) ^ 0x1021) if c & 0x8000 else (c << 1)
            c &= 0xFFFF
        t.append(c)
    return t


def crc32_table():
    t = []
    for i in range(256):
        c = i
        for _ in range(8):
            c = (c >> 1) ^ 0xEDB88320 if c & 1 else c >> 1
        t.append(c)
    return t


def fmt(vals, width):
    lines = []
    for i in range(0, len(vals), 8):
        lines.append("    " + ", ".join(("0x%0" + str(width) + "X") % v for v in vals[i:i + 8]) + ",")
    return "\n".join(lines)


SRC = """/*
 * alfp_crc_tables.c - lookup tables for CRC-16/CCITT-FALSE and CRC-32 (IEEE).
 * Generated by tools/gen_crc_tables.py. Stored as const so they live in flash,
 * not RAM.
 */
#include <stdint.h>

const uint16_t g_alfp_crc16_table[256] = {
%s
};

const uint32_t g_alfp_crc32_table[256] = {
%s
};
"""

if __name__ == "__main__":
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "alfp", "src", "alfp_crc_tables.c")
    with open(out, "w") as f:
        f.write(SRC % (fmt(crc16_table(), 4), fmt(crc32_table(), 8)))
    finish_c_file(Path(out))
    print("wrote", out)
