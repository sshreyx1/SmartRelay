#!/usr/bin/env python3
"""
gen_sound_tables.py - generate firmware/sensing/sound_tables.c: the Q15 twiddle factors and Hann
window for the 256-point FFT in sound_fft.c / sound_features.c. The output is checked in; run this
only if SOUND_FFT_N changes.

Run:      python tools/gen_sound_tables.py
"""
import argparse
import math
from pathlib import Path

from c_style import finish_c_file

N = 256
OUT = Path(__file__).resolve().parent.parent / "firmware" / "sensing" / "sound_tables.c"


def q15(v: float) -> int:
    return max(-32768, min(32767, int(round(v * 32768.0))))


def rows(vals, per_line=12):
    out = []
    for i in range(0, len(vals), per_line):
        out.append("    " + ", ".join(f"{v:6d}" for v in vals[i:i + per_line]) + ",")
    return "\n".join(out)


def main() -> None:
    argparse.ArgumentParser(description="Generate firmware/sensing/sound_tables.c (Q15 FFT twiddles + Hann).").parse_args()
    cos_t = [q15(math.cos(2 * math.pi * k / N)) for k in range(N // 2)]
    sin_t = [q15(math.sin(2 * math.pi * k / N)) for k in range(N // 2)]
    hann = [q15(0.5 - 0.5 * math.cos(2 * math.pi * n / N)) for n in range(N)]  # periodic Hann
    text = f"""/*
 * sound_tables.c - GENERATED by tools/gen_sound_tables.py, do not edit by hand.
 * Q15 tables for the {N}-point FFT (sound_fft.c) and its window
 * (sound_features.c).
 */
#include "sound_tables.h"

/* cos(2*pi*k/{N}) and sin(2*pi*k/{N}), k = 0..{N // 2 - 1}, Q15 (1.0 saturates to
 * 32767) */
const int16_t g_sound_twiddle_cos[SOUND_FFT_N / 2] = {{
{rows(cos_t)}
}};

const int16_t g_sound_twiddle_sin[SOUND_FFT_N / 2] = {{
{rows(sin_t)}
}};

/* periodic Hann window 0.5 - 0.5*cos(2*pi*n/{N}), Q15 */
const int16_t g_sound_hann_q15[SOUND_FFT_N] = {{
{rows(hann)}
}};
"""
    OUT.write_text(text, encoding="utf-8", newline="\n")
    finish_c_file(OUT)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
